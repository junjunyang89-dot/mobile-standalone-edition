def build_decompose_guide(doc):
    add_book_title(doc, "物理拆题四步法 ★（全书通用）")

    add_chapter_title(doc, "第一步：圈词 — 找已知、未知、关键词")
    add_concept_block(doc, [
        "**已知量**：题目直接给出的数据（带单位），如 v=72 km/h、t=0.5 h。",
        "**未知量**：题目所求，如求 s、ρ、P、I。",
        "**关键词**：决定用哪章哪条规律——**匀速**→v=s/t；**同一物质**→ρ相同；**平衡/静止**→F合=0；**串联**→I相等；**并联**→U相等。",
        "**图像题**：看坐标轴物理量、斜率含义、交点、水平段（常表示匀速或不变）。",
    ])

    add_chapter_title(doc, "第二步：判类型 — 选章节、选公式")
    add_table(doc, ["关键词/情境", "所属章节", "首选公式/规律"], [
        ["路程、时间、速度", "机械运动", "v=s/t"],
        ["质量、体积、密度", "质量与密度", "ρ=m/V"],
        ["力、重力、摩擦力", "力/运动和力", "G=mg；二力平衡"],
        ["压强、液柱、大气压", "压强", "p=F/S；p=ρgh"],
        ["浮沉、排水量", "浮力", "F浮=ρ液gV排；浮沉条件"],
        ["功、功率、机械能", "功和机械能", "W=Fs；P=W/t"],
        ["电流、电压、电阻", "电路/欧姆定律", "I=U/R；串联并联规律"],
        ["电功率、电能", "电功率", "P=UI；W=Pt"],
    ], [3.5, 3, 6])

    add_chapter_title(doc, "第三步：找关系等式 + 隐藏数据")
    add_method_block(doc, [
        "**列主等式**：根据所求量，写出核心公式（如求 ρ → ρ=m/V）。",
        "**找中间量**：若缺 m 或 V，看能否从题中其他条件得到（如 V=V₂−V₁ 排水法）。",
        "**隐藏数据清单**（高频）：",
        "　· **同一物质/均匀物体** → ρ 不变；",
        "　· **匀速直线运动** → v 不变，s 与 t 成正比；",
        "　· **水平静止** → 支持力 F=G，摩擦力与拉力平衡（若匀速拉动）；",
        "　· **完全浸没** → V排=V物；",
        "　· **串联电路** → 电流处处相等，U总=U₁+U₂；",
        "　· **并联电路** → 各支路电压相等，I总=I₁+I₂；",
        "　· **标准大气压** p₀=1.0×10⁵ Pa；**g** 取 10 N/kg（除非题目另给 9.8）。",
        "**比例题**：m₁/m₂=ρV₁/ρV₂，同物质则 m 与 V 成正比。",
    ])

    add_chapter_title(doc, "第四步：列式求解 + 检验")
    add_method_block(doc, [
        "① 统一单位（km/h→m/s：÷3.6；cm³→m³：×10⁻⁶；g→kg：÷1000）。",
        "② 代入公式计算，结果带单位。",
        "③ **检验**：数量级是否合理（密度约 10³ kg/m³ 量级；人步行 v≈1 m/s）。",
        "④ 选择题：排除单位错、概念反了（如虚像能成在光屏上——错）。",
    ])

    add_decompose_example(
        doc,
        "一实心金属块质量 540 g，体积 200 cm³，求该金属的密度（kg/m³）。",
        [
            ("圈词", "已知 m=540 g，V=200 cm³；求 ρ"),
            ("判类型", "质量与密度 → ρ=m/V"),
            ("找关系", "m 需换 kg：0.54 kg；V 需换 m³：200×10⁻⁶ m³"),
            ("列式", "ρ=0.54/(200×10⁻⁶)"),
        ],
        "ρ = m/V",
        "隐藏：题目给 g、cm³，计算密度标准单位需换 kg、m³",
        "ρ = 0.54 kg / (200×10⁻⁶ m³) = **2.7×10³ kg/m³**（铝）",
    )


