def _chapter_22(doc):
    add_chapter_title(doc, "第二十二章 二次函数")

    add_concept_block(doc, [
        "**二次函数**：y=ax²+bx+c（a≠0）；自变量x，函数值y。",
        "**图象——抛物线**：a>0开口向上，有**最小值**；a<0开口向下，有**最大值**。",
        "**顶点坐标**：(-b/(2a), (4ac−b²)/(4a))；对称轴直线 x=−b/(2a)。",
        "**顶点式**：y=a(x−h)²+k，顶点**(h,k)**；a>0时k为最小值，a<0时k为最大值。",
        "**与y轴交点**：(0,c)；**与x轴交点**：解ax²+bx+c=0，个数由Δ决定。",
        "**平移**：y=a(x−h)²+k由y=ax²向右平移h、向上平移k（h<0向左，k<0向下）。",
        "**最值问题**：配方或公式求顶点纵坐标；应用题注意自变量**取值范围**。",
        "**与一元二次方程关系**：ax²+bx+c=0的解是抛物线与x轴交点的横坐标。",
    ])

    add_formula_block(doc, [
        ("一般式", "y = ax² + bx + c (a≠0)"),
        ("顶点式", "y = a(x−h)² + k，顶点(h,k)"),
        ("对称轴", "x = −b/(2a)"),
        ("最值", "a>0：最小值=(4ac−b²)/(4a)；a<0：最大值同上"),
        ("交点式", "y=a(x−x₁)(x−x₂)，x₁、x₂为与x轴交点横坐标"),
    ])

    add_method_block(doc, [
        "**化顶点式**：配方 y=a(x²+(b/a)x)+c → y=a(x+b/(2a))²+(4ac−b²)/(4a)。",
        "**画图象**：先定顶点、对称轴，再取对称点列表描点。",
        "**求解析式**：已知三点用一般式；已知顶点+一点用顶点式；已知与x轴两交点+一点用交点式。",
        "**最值应用**：建立二次函数模型，看顶点是否在自变量范围内；在范围内比较端点与顶点。",
    ])

    add_mistake_problems(doc, [
        (
            "y=−2(x−3)²+5的最大值是多少？",
            "看到5就写最大值5，忽略a的符号。",
            "a=−2<0，开口向下，顶点(3,5)处取**最大值5**。",
        ),
        (
            "抛物线y=x²−4x+3的对称轴。",
            "对称轴x=4或x=3。",
            "x=−b/(2a)=4/2=**2**（对称轴是直线，写x=2）。",
        ),
        (
            "将y=x²向右平移2个单位。",
            "写y=(x+2)²。",
            "右移2：y=**(x−2)²**（左加右减针对x）。",
        ),
    ])

    add_advanced_problems(doc, [
        (
            "用20 m长的篱笆围矩形菜园，一边靠墙（墙足够长），求最大面积。",
            "设垂直墙边长x，则平行墙边(20−2x)，面积S=x(20−2x)=−2x²+20x。",
            "x=5时，最大面积**50 m²**。",
        ),
        (
            "抛物线过(0,3)、(1,0)、(3,0)，求解析式。",
            "交点式y=a(x−1)(x−3)，代入(0,3)求a。",
            "y=**(x−1)(x−3)**=x²−4x+3。",
        ),
    ])

    add_errors(doc, [
        "二次函数**必须**a≠0；y=ax²+bx+c中a决定开口方向与大小。",
        "平移规律：**左加右减、上加下减**（对括号内x和整体k）。",
        "最值问题注意定义域，顶点不在范围内要比较**端点值**。",
        "对称轴是**直线方程**x=−b/(2a)，不是点的坐标。",
    ])
    add_exam_types(doc, [
        "求抛物线顶点、对称轴、开口方向",
        "二次函数解析式待定系数",
        "二次函数最值（面积、利润）",
        "二次函数与一元二次方程、不等式",
    ])


