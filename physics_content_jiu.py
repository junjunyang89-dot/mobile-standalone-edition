    add_concept_block(doc, [
        "**家庭电路**：220 V；火线（L）零线（N）；**地线**保护；**保险丝/空气开关**过载保护。",
        "**安全用电**：不接触低压带电体、不靠近高压；**湿手不触电**；开关接火线。",
        "**磁现象**：磁体有 N、S 极；同名相斥异名相吸；磁感线从 N 出 S 入（闭合曲线）。",
        "**电流磁效应**：通电导线周围有磁场；**奥斯特实验**。",
        "**电磁铁**：电流+铁芯；电流越大、匝数越多，磁性越强。",
        "**电动机**：**通电导体在磁场中受力**转动；能量：电能→机械能。",
        "**发电机**：**电磁感应**产生电流；能量：机械能→电能。",
        "**电磁感应**：闭合电路一部分导体在磁场中**切割磁感线**→感应电流。",
        "**电磁波**：信息传递；真空中 c=3×10⁸ m/s；λ=c/f。",
        "**能源**：可再生能源（水能、太阳能、风能）；不可再生（煤、石油、天然气）；**可持续发展**。",
    ])
    add_experiment_block(doc, [
        "**探究导体在磁场中受力方向**：与**电流方向、磁场方向**有关（左手定则拓展）。",
        "**探究感应电流条件**：闭合、切割磁感线。",
    ])
    add_exam_types(doc, [
        "家庭电路连接与安全",
        "电磁铁强弱因素",
        "电动机与发电机原理区分",
        "电磁感应条件",
    ])


