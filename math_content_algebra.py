def build_algebra_guide(doc):
    add_book_title(doc, "专题二：代数方法归纳")
    add_plain(doc,
                "代数题核心：**识别类型 → 选方法 → 规范计算 → 检验**。"
                "计算题抓符号；方程抓变形；函数抓数形结合。")

    add_chapter_title(doc, "一、计算类速查")
    add_formula_block(doc, [
        ("有理数", "先定符号，再算绝对值；乘方优先级高于乘除"),
        ("去括号", "括号前「+」不变号；「−」全变号"),
        ("合并同类项", "只合并字母和指数相同的项"),
        ("幂的运算", "aᵐ·aⁿ=aᵐ⁺ⁿ；(aᵐ)ⁿ=aᵐⁿ；(ab)ⁿ=aⁿbⁿ"),
        ("乘法公式", "(a±b)²=a²±2ab+b²；a²−b²=(a+b)(a−b)"),
        ("分式", "分母≠0；约分先因式分解；加减通分"),
        ("二次根式", "√(ab)=√a·√b；√(a/b)=√a/√b；分母有理化"),
    ])

    add_method_block(doc, [
        "**计算题自检**：① 有无符号错 ② 括号是否去净 ③ 能否约分 ④ 代入特殊值检验",
        "**因式分解顺序**：提公因式 → 公式法 → 十字相乘 → 分组",
        "**解方程流程**：去分母→去括号→移项→合并→系数化1→**检验**（分式、无理要验）",
        "**解不等式**：变号规则——乘除**负数**时不等号方向改变",
        "**解方程组**：看系数——代入法（系数为1）；加减消元（系数成倍数）",
    ])

    add_chapter_title(doc, "二、函数与方程")
    add_table(doc, ["类型", "关键", "方法"], [
        ["一次函数 y=kx+b", "k定倾斜，b定截距", "待定系数法求解析式；联立方程求交点"],
        ["一元二次方程", "Δ=b²−4ac", "因式分解→公式法→配方法；验根"],
        ["二次函数", "顶点式 y=a(x−h)²+k", "配方求最值；a>0开口向上"],
        ["反比例函数 y=k/x", "k>0一三象限", "k=xy；与一次函数联立"],
    ], [3, 4, 6])

    add_errors(doc, [
        "去括号只变第一项符号。",
        "不等式两边乘−1忘记变号。",
        "分式方程解完不检验，增根当正解。",
        "二次函数把a的符号看错（开口方向）。",
    ])


def build_word_problem_guide(doc):
    add_book_title(doc, "专题三：应用题拆题训练（独立拆题→再解题）")
    add_plain(doc,
                "**强烈建议的学习顺序**（您提出的方法非常对）：\n"
                "① 只读题，完成下面四个「□」  ② 再翻答案对拆题  ③ 最后自己完整解一遍\n"
                "应用题不会，80%是**不会拆题**，不是不会算。")

    add_chapter_title(doc, "万能拆题四步法")
    add_table(doc, ["步骤", "做什么", "示例关键词"], [
        ["① 读题圈词", "谁？多少？关系？", "原来、又、共、比…多、剩下"],
        ["② 判类型", "行程/工程/利润/配套…", "见下表"],
        ["③ 找等量关系", "找一句能把前后连起来的等式", "路程相等、总量相等"],
        ["④ 设元列式", "设什么最简单", "设时间t、设速度x"],
    ], [2.5, 4.5, 6.5])

    add_chapter_title(doc, "应用题类型速查表")
    add_table(doc, ["类型", "等量关系", "设元建议"], [
        ["行程·相遇", "甲路程+乙路程=总路程", "设时间t"],
        ["行程·追及", "快者路程−慢者路程=相差距离", "设时间t"],
        ["工程", "效率×时间=工作量（总量为1）", "设甲单独做x天完成"],
        ["利润", "售价−进价=利润；利润率=利润/进价", "设进价或售价"],
        ["配套", "两种物品按比配套，总量关系", "设生产某品x件"],
        ["增长率", "现量=原量×(1+率)ⁿ", "设原量或年数"],
        ["几何应用", "勾股、面积、周长公式", "设边长x"],
        ["一次函数应用", "两个变量线性关系", "设解析式或实际量"],
    ], [2.5, 5.5, 5.5])

    add_chapter_title(doc, "拆题练习 · 七年级")

    add_decompose_drill(doc, 1,
                      "甲、乙两地相距360 km，两车同时相向而行，甲速60 km/h，乙速40 km/h，几小时相遇？",
                      [("圈词", "相距、相向、相遇"),
                       ("判类型", "行程·相遇"),
                       ("等量关系", "甲路程+乙路程=360"),
                       ("设元列式", "设t小时，60t+40t=360")],
                      "相向→相遇模型；总路程=各自行程之和",
                      "60t+40t=360 → t=**3.6小时**")

    add_decompose_drill(doc, 2,
                      "小明买10个笔记本和5支笔共花35元，笔记本比笔贵1元，求各单价。",
                      [("圈词", "共、比…贵"),
                       ("判类型", "配套/二元"),
                       ("等量关系", "10本+5笔=35；本价=笔价+1"),
                       ("设元", "设笔x元，本(x+1)元")],
                      "两个未知量，两个等量关系→方程组",
                      "x=2，本3元；笔**2元/支**，本**3元/个**")

    add_decompose_drill(doc, 3,
                      "工人铺一条管道，甲队单独做需12天，乙队单独做需18天，两队合作几天完成？",
                      [("圈词", "单独、合作、完成"),
                       ("判类型", "工程问题"),
                       ("等量关系", "甲效率×t+乙效率×t=1（总量）"),
                       ("设元", "设t天，1/12·t+1/18·t=1")],
                      "效率=1/单独天数；合作效率相加",
                      "t=**7.2天**（或36/5天）")

    add_chapter_title(doc, "拆题练习 · 八年级")

    add_decompose_drill(doc, 4,
                      "商品进价100元，按20%利润率定价，打9折后售，实际利润率多少？",
                      [("圈词", "进价、利润率、定价、打折"),
                       ("判类型", "利润"),
                       ("等量关系", "售价=进价×(1+利润率)；打折后售价=定价×0.9"),
                       ("列式", "定价120，售108，利润8，率8%")],
                      "利润率=利润÷进价（不是÷售价）",
                      "定价120元，售108元，利润8元，利润率=8/100=**8%**")

    add_decompose_drill(doc, 5,
                      "等腰三角形周长20 cm，底边比腰长2 cm，求三边。",
                      [("圈词", "等腰、周长、比…长"),
                       ("判类型", "几何+方程"),
                       ("等量关系", "腰+腰+底=20；底=腰+2"),
                       ("设元", "设腰x，底x+2")],
                      "等腰两边相等；需检验能否构成三角形",
                      "腰6，底8；**6,6,8**（若腰5底10则5+5=10不行）")

    add_decompose_drill(doc, 6,
                      "某商品进价40元，按50元售出，每天可卖500件。每涨1元少卖10件。求每价多少时利润最大？",
                      [("圈词", "进价、售价、涨、少卖、最大"),
                       ("判类型", "二次函数应用（九上也可）"),
                       ("等量关系", "利润=(售价−进价)×销量；销量=500−10×涨价额"),
                       ("设元", "设涨x元，利润=(10+x)(500−10x)")],
                      "建立二次函数求顶点；或配方法",
                      "涨5元时最大，最大利润**2250元**（模型题，具体以展开为准）")

    add_chapter_title(doc, "拆题练习 · 九年级")

    add_decompose_drill(doc, 7,
                      "矩形长比宽多2 m，面积48 m²，求长宽。",
                      [("圈词", "矩形、比…多、面积"),
                       ("判类型", "一元二次方程几何应用"),
                       ("等量关系", "长×宽=48；长=宽+2"),
                       ("设元", "设宽x，长x+2，x(x+2)=48")],
                      "面积问题→方程；Δ≥0且根为正",
                      "宽6 m，长**8 m**（x=6，x=−8舍）")

    add_decompose_drill(doc, 8,
                      "某厂今年产值100万，计划每年增长率8%，几年后产值达约146万？",
                      [("圈词", "增长率、几年后"),
                       ("判类型", "增长率"),
                       ("等量关系", "现量=100×(1.08)ⁿ=146"),
                       ("求解", "试算或方程")],
                      "增长率复合：原量×(1+r)ⁿ",
                      "n≈**5年**（100×1.08⁵≈146.9）")

    add_chapter_title(doc, "家长/孩子使用说明")
    add_plain(doc, "**第一遍**：只看题目，强制填四个□，不会也写「我猜是…类型」")
    add_plain(doc, "**第二遍**：对「拆题思路」，用红笔改")
    add_plain(doc, "**第三遍**：遮住答案，完整写解题过程")
    add_plain(doc, "**每周**：至少练3道应用题拆题，比刷10道整卷更有效")

    add_exam_types(doc, [
        "相遇追及（设时间）",
        "工程问题（效率相加）",
        "利润打折（分清基准量）",
        "配套方程组",
        "增长率列方程",
        "几何面积周长列方程",
    ])
