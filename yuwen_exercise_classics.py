def _book_exercises(doc, book_title, questions, answers):
    add_exercise_unit(doc, book_title)
    for i, q in enumerate(questions, 1):
        if isinstance(q, tuple) and len(q) == 2 and isinstance(q[1], list):
            add_choice_question(doc, i, q[0], q[1])
        elif isinstance(q, tuple):
            add_question(doc, i, q[0])
        else:
            add_question(doc, i, q)
    add_answers(doc, f"【参考答案·{book_title}】", answers)


