# -*- coding: utf-8 -*-
"""物理经典必考题型专练：匀速/变速、小球下落、汽车运动、相机透镜。"""

from physics_doc_helpers import (
    add_book_title,
    add_chapter_title,
    add_plain,
    add_decompose_drill,
    add_table,
    add_errors,
    add_method_block,
    add_figure,
)


def _add_drills(doc, drills, start=1):
    for i, d in enumerate(drills, start):
        fig = d[4] if len(d) > 4 else None
        add_decompose_drill(doc, i, d[0], d[1], d[2], d[3], figure_id=fig)


def build_drill_classics(doc):
    add_book_title(doc, "专篇 · 经典必考题型 ★（匀速/变速·小球·汽车·相机）")

    add_plain(doc, "以下是人教版八上**最高频**题型：图像判断、频闪照片、过桥追及、透镜三种应用。每题**先看图**，再拆题。")

    add_chapter_title(doc, "一、匀速运动 vs 变速运动（s-t / v-t 图像）")
    add_method_block(doc, [
        "**s-t 图**：过原点**直线**→匀速；**曲线**向上弯→变速（加速，路程增加越来越快）；**水平线**→静止。",
        "**v-t 图**：**水平线**→匀速；**倾斜上升**→加速（拓展）；**与 t 轴围成面积**→路程。",
        "**平均速度**（变速）：v̄ = **总路程 / 总时间**（不是两个速度直接平均！）。",
    ])
    add_table(doc, ["图像", "运动性质", "判断依据"], [
        ["s-t 过原点直线", "匀速直线", "斜率 k = v 不变"],
        ["s-t 曲线向上弯", "变速（加速）", "相同时间路程增量变大"],
        ["s-t 水平线", "静止", "s 不随 t 变"],
        ["v-t 水平线", "匀速", "v 不变"],
        ["v-t 斜线上升", "匀加速（拓展）", "v 随 t 增大"],
    ], [3, 3, 5])

    drills_motion = [
        ("见 s-t 图像：过原点的直线，说明什么运动？如何求速度？",
         [("圈词", "s-t、过原点、直线"), ("判类型", "匀速直线运动"), ("关系", "斜率 k=Δs/Δt=v"), ("结论", "读斜率")],
         "直线→匀速；斜率=速度",
         "**匀速直线运动**；v = **s/t** = 图像**斜率**",
         "st_uniform"),
        ("见 s-t 图像：向上弯曲的曲线，说明什么运动？",
         [("圈词", "曲线、向上弯"), ("判类型", "变速运动"), ("特征", "相同Δt内Δs越来越大"), ("结论", "加速")],
         "曲线→变速；弯向上→加速",
         "**变速运动**（加速），**不是**匀速",
         "st_variable"),
        ("见 s-t 图像：水平线段，说明什么运动？",
         [("圈词", "水平"), ("判类型", "静止"), ("关系", "s 不变"), ("结论", "v=0")],
         "水平→s 不随 t 变",
         "**静止**（或该段时间内没有位移）",
         "st_rest"),
        ("甲、乙 s-t 图像：甲的直线比乙陡，说明什么？",
         [("圈词", "斜率比较"), ("判类型", "匀速比较快慢"), ("关系", "斜率大→v大"), ("结论", "甲更快")],
         "斜率 = v",
         "**甲**运动更快（斜率更大）",
         "st_compare"),
        ("v-t 图像为水平线，5 s 内 v=4 m/s，求这段时间通过的路程。",
         [("圈词", "v-t 水平"), ("判类型", "匀速"), ("关系", "s=vt 或 面积"), ("列式", "s=4×5")],
         "v-t 水平→匀速；面积=s",
         "s = **20 m**",
         "vt_uniform"),
        ("某物体前 2 s 通过 8 m，后 3 s 通过 12 m，求 5 s 内平均速度。",
         [("圈词", "两段路程"), ("判类型", "平均速度"), ("关系", "v̄=s总/t总"), ("列式", "20/5")],
         "变速→用总路程/总时间",
         "v̄ = (8+12)/5 = **4 m/s**",
         None),
        ("小明上学家，前一半路程以 2 m/s 走，后一半路程以 3 m/s 走，求全程平均速度（设全程 2s）。",
         [("圈词", "一半路程"), ("判类型", "平均速度"), ("时间", "t1=s/2，t2=s/2"), ("v̄", "2s/(s/2+s/3)")],
         "v̄=s总/t总；t总=t1+t2",
         "v̄ = 2/(1/2+1/3) = **2.4 m/s**（不是 2.5）",
         None),
    ]
    _add_drills(doc, drills_motion, 1)

    add_chapter_title(doc, "二、小球下落与频闪照片 ★必考")
    add_method_block(doc, [
        "**频闪照片**：照相机等时间间隔闪光，记录物体位置。",
        "**相邻间距相等**→**匀速**；**间距越来越大**→**变速（加速）**。",
        "**自由下落**（忽略空气阻力）：是**加速**运动，相邻相等时间内下落距离之比为 **1:3:5:7…**（奇数比）。",
        "注意：初中计算题若只给总高度和总时间，仍用 v̄=s/t；奇数比用于**定性判断**和**实验分析题**。",
    ])

    drills_ball = [
        ("频闪照片显示小球相邻两次位置间距越来越大，小球做什么运动？",
         [("圈词", "间距越来越大"), ("判类型", "变速"), ("结论", "加速"), ("反例", "间距相等才是匀速")],
         "间距增大→相同时间内路程变大→加速",
         "**变速运动**（**加速**）",
         "ball_strobe_fall"),
        ("频闪照片中小球相邻间距始终相等，可能是什么运动？",
         [("圈词", "间距相等"), ("判类型", "匀速"), ("注意", "也可能是拍照角度问题"), ("结论", "匀速")],
         "相等间距→相等时间路程相等",
         "**匀速直线运动**",
         "ball_strobe_uniform"),
        ("自由下落过程中，每经过相等时间，下落距离之比 1:3:5:7 说明什么？",
         [("圈词", "奇数比"), ("判类型", "加速"), ("含义", "相同时间位移增量递增"), ("结论", "加速")],
         "奇数比→加速下落",
         "说明小球做**加速运动**（自由下落）",
         "ball_fall_distances"),
        ("小球从 20 m 高处自由下落，忽略空气阻力，5 s 末落地，求全程平均速度。",
         [("圈词", "总高 20 m，总时 5 s"), ("判类型", "平均速度"), ("列式", "v̄=20/5"), ("注意", "不是匀速4m/s")],
         "自由下落是加速；平均速度=总s/总t",
         "v̄ = **4 m/s**（平均速度，非某一时刻速度）",
         "ball_strobe_fall"),
        ("在 1 s、2 s、3 s 内下落的距离若成 1:3:5，第 1 s 下落 2 m，求前 3 s 总路程。",
         [("圈词", "1:3:5"), ("判类型", "比例"), ("列式", "2+6+10"), ("总", "18 m")],
         "按奇数比：2m, 6m, 10m",
         "s总 = 2+6+10 = **18 m**",
         "ball_fall_distances"),
    ]
    _add_drills(doc, drills_ball, len(drills_motion) + 1)

    add_chapter_title(doc, "三、汽车运动经典题 ★")
    add_method_block(doc, [
        "**完全通过桥/隧道**：s = **桥长 + 车长**（从车头进入到车尾离开）。",
        "**相向而行**：s = (v1+v2)·t；**同向追及**：s = (v快−v慢)·t。",
        "**往返平均速度**：v̄ = **2s / (t去+t回)**，不是 (v1+v2)/2。",
    ])

    drills_car = [
        ("长 200 m 的火车以 20 m/s 匀速通过长 1800 m 的隧道，求完全通过隧道的时间。",
         [("圈词", "完全通过"), ("判类型", "s=vt"), ("隐藏", "s=200+1800=2000 m"), ("列式", "t=2000/20")],
         "完全通过→加车长",
         "t = **100 s**",
         "car_bridge"),
        ("两汽车相距 300 km 相向而行，甲 60 km/h，乙 40 km/h，几小时相遇？",
         [("圈词", "相向"), ("判类型", "相遇"), ("方程", "(60+40)t=300"), ("解", "3 h")],
         "相遇：速度和×t=总距",
         "t = **3 h**",
         "car_meeting"),
        ("甲车在前以 15 m/s 行驶，乙车同向以 25 m/s 行驶，相距 200 m，乙何时追上甲？",
         [("圈词", "同向、追上"), ("判类型", "追及"), ("方程", "(25−15)t=200"), ("解", "20 s")],
         "追及：(v快−v慢)t=s",
         "t = **20 s**",
         "car_chase"),
        ("汽车 0～1 h 行驶 40 km，1～3 h 休息，3～4 h 又行驶 60 km，求全程平均速度。",
         [("圈词", "多段、休息"), ("判类型", "v̄=s总/t总"), ("s总", "100 km"), ("t总", "4 h")],
         "休息时间也算进总时间",
         "v̄ = 100/4 = **25 km/h**",
         "car_multisegment"),
        ("甲乙两地相距 120 km，去时 60 km/h，返回 40 km/h，求往返平均速度。",
         [("圈词", "往返"), ("判类型", "平均速度"), ("s总", "240 km"), ("t总", "2+3=5 h")],
         "v̄=2s/(s/v1+s/v2)",
         "v̄ = 240/5 = **48 km/h**（不是 50）",
         "car_roundtrip"),
        ("说「车上的乘客是静止的」，应选什么作参照物？相对地面呢？",
         [("圈词", "静止、参照物"), ("判类型", "概念"), ("静止", "选车"), ("运动", "选地面")],
         "参照物不同，结论不同",
         "静止→参照物**车**；相对**地面****运动**",
         "reference_frame"),
        ("汽车以 72 km/h 匀速，通过长 500 m 的大桥，车长忽略，求通过时间。",
         [("圈词", "72 km/h，桥 500 m"), ("判类型", "s=vt"), ("换单位", "72/3.6=20 m/s"), ("t", "500/20")],
         "无车长→s=桥长",
         "t = **25 s**",
         "car_bridge"),
    ]
    _add_drills(doc, drills_car, len(drills_motion) + len(drills_ball) + 1)

    add_chapter_title(doc, "四、照相机·投影仪·放大镜 ★必考")
    from physics_figure_draw import ensure_figure
    add_figure(doc, ensure_figure("lens_three_apps"), "凸透镜三种应用对照表")

    add_method_block(doc, [
        "**照相机**：物距 **u > 2f** → **倒立、缩小、实像**（像成在底片/传感器上）。",
        "**投影仪/幻灯机**：**f < u < 2f** → **倒立、放大、实像**（投到屏幕上）。",
        "**放大镜**：**u < f** → **正立、放大、虚像**（眼睛在透镜同侧看）。",
        "**记忆**：实像都能成在光屏上；虚像不能。照相机拍远处风景，u 很大。",
    ])

    drills_lens = [
        ("用照相机拍摄远处景物，物距 u 与焦距 f 关系？成什么像？",
         [("圈词", "照相机、远处"), ("判类型", "u>2f"), ("像", "倒立缩小实像"), ("应用", "相机")],
         "远处→u>2f",
         "**u > 2f**；**倒立、缩小、实像**",
         "lens_camera"),
        ("投影仪使屏幕上出现放大的像，物距应满足什么条件？",
         [("圈词", "投影仪、放大实像"), ("判类型", "f<u<2f"), ("像", "倒立放大实像")],
         "放大实像→投影仪模型",
         "**f < u < 2f**；**倒立、放大、实像**",
         "lens_projector"),
        ("用放大镜看邮票，应把邮票放在距透镜多少范围内？成什么像？",
         [("圈词", "放大镜"), ("判类型", "u<f"), ("像", "正立放大虚像")],
         "放大镜 u<f",
         "**u < f**；**正立、放大、虚像**",
         "lens_magnifier"),
        ("凸透镜 f=10 cm，物距 25 cm，像的性质和应用分别是什么？",
         [("圈词", "f=10，u=25"), ("比较", "u>2f"), ("像", "倒立缩小实像"), ("应用", "照相机")],
         "25>20=2f",
         "**倒立缩小实像**；**照相机**",
         "lens_camera"),
        ("凸透镜 f=10 cm，物距 15 cm，像在何处？应用？",
         [("圈词", "u=15"), ("比较", "f<u<2f"), ("像", "倒立放大实像"), ("应用", "投影仪")],
         "10<15<20",
         "**倒立放大实像**；**投影仪**",
         "lens_projector"),
        ("凸透镜 f=10 cm，物距 8 cm，像的性质？",
         [("圈词", "u=8<f"), ("判类型", "虚像"), ("结论", "正立放大虚像")],
         "u<f→放大镜",
         "**正立、放大、虚像**（**放大镜**）",
         "lens_magnifier"),
        ("下列哪种情况能成在光屏上？A.照相机 B.放大镜 C.平面镜",
         [("圈词", "光屏、实像"), ("分析", "实像才能成屏上"), ("排除", "放大镜虚像、平面镜虚像")],
         "实像→光屏",
         "选 **A 照相机**（成实像）",
         "lens_three_apps"),
    ]
    _add_drills(doc, drills_lens, len(drills_motion) + len(drills_ball) + len(drills_car) + 1)

    add_errors(doc, [
        "把 s-t **曲线**当成匀速——曲线是**变速**。",
        "频闪照片**间距变大**不是匀速，是**加速**（小球下落必考）。",
        "往返平均速度**不能** (v1+v2)/2，要用**总路程/总时间**。",
        "照相机成**倒立**像，不是正立；放大镜才是正立**虚**像。",
        "「通过隧道」忘记加**车长**——完全通过必须加。",
    ])
