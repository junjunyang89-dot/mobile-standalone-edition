def _chapter_7(doc):
    add_chapter_title(doc, "第七章 力")

    add_concept_block(doc, [
        "**力**：物体对物体的作用；单位 **N（牛顿）**；力不能脱离物体存在。",
        "**作用效果**：①改变物体形状；②改变物体运动状态。",
        "**三要素**：大小、方向、作用点；用**力的示意图**表示（带箭头线段）。",
        "**相互作用力**：大小相等、方向相反、作用在不同物体上（如手推墙，墙推手）。",
        "**弹力**：形变产生的力；**弹簧测力计**原理——在弹性限度内，伸长与拉力成正比。",
        "**重力 G**：地球吸引；**G=mg**；方向**竖直向下**；g≈10 N/kg。",
        "**重心**：重力作用点；规则均匀物体在几何中心。",
    ])
    add_formula_block(doc, [
        ("重力", "G = mg"),
        ("质量", "m = G/g"),
    ])
    add_experiment_block(doc, [
        "**弹簧测力计使用**：调零 → 沿轴线拉 → 读数（视线垂直）。",
        "**探究 G 与 m 关系**：G/m 为定值 → g 恒定。",
    ])
    add_exam_types(doc, [
        "力的示意图作图",
        "G=mg 计算",
        "相互作用力判断",
        "弹簧测力计读数",
    ])


def _chapter_8(doc):
    add_chapter_title(doc, "第八章 运动和力")

    add_concept_block(doc, [
        "**牛顿第一定律（惯性定律）**：一切物体在没有受到力的作用时，总保持**静止或匀速直线运动**状态。",
        "**惯性**：物体保持原运动状态的性质；**只与质量有关**，质量越大惯性越大。",
        "**惯性不是力**，不能说「受到惯性作用」。",
        "**二力平衡**：同一物体、两力**等大反向共线** → 静止或匀速直线运动。",
        "**平衡力与相互作用力区别**：平衡力在**同一物体**上；相互作用力在**两个物体**上。",
        "**摩擦力**：阻碍相对运动的力；**滑动摩擦**、**静摩擦**。",
        "**滑动摩擦力**与**压力**和**接触面粗糙程度**有关；与速度、接触面积（一般）无关。",
        "**增大摩擦**：增大压力、增大粗糙程度；**减小摩擦**：减小压力、变滑动为滚动、加润滑油。",
    ])
    add_method_block(doc, [
        "**判断平衡**：物体静止或匀速 → 所受合力为 0 → 二力平衡。",
        "**受力分析**：重力竖直向下 → 支持力 → 拉力/摩擦力 → 画图。",
    ])
    add_mistake_problems(doc, [
        (
            "汽车急刹车时乘客前倾，是因为受到向前的力吗？",
            "答受到惯性力向前。",
            "因**惯性**保持原运动状态；**不是**受到额外向前的力。",
        ),
        (
            "匀速拉动物体，拉力 F 与摩擦力 f 的关系？",
            "F>f 才能动。",
            "匀速时 **F=f**（二力平衡）。",
        ),
    ])
    add_exam_types(doc, [
        "惯性现象解释",
        "二力平衡条件",
        "摩擦力影响因素（控制变量）",
        "受力分析作图",
    ])


def _chapter_9(doc):
    add_chapter_title(doc, "第九章 压强")

    add_concept_block(doc, [
        "**压力 F**：垂直压在物体表面上的力；不一定等于重力（如斜面、顶墙）。",
        "**压强 p**：压力的作用效果；**p=F/S**；单位 **Pa（帕斯卡）**；1 Pa=1 N/m²。",
        "**增大压强**：增大 F 或减小 S（针尖、刀刃）；**减小压强**：增大 S（书包背带）。",
        "**液体压强**：**p=ρgh**；与深度 h 有关，与容器形状、液体质量无关（同深度各向相等）。",
        "**连通器**：上端开口、底部连通；同种液体静止时**液面相平**（船闸、茶壶）。",
        "**大气压**：空气产生的压强；**p₀≈1.0×10⁵ Pa**；托里拆利实验测大气压。",
        "**流体压强**：流速大处压强**小**（飞机升力、喷雾器）。",
    ])
    add_formula_block(doc, [
        ("压强", "p = F/S"),
        ("液体压强", "p = ρgh"),
        ("柱体压强（固）", "p = ρgh（均匀柱体对底面）"),
    ])
    add_decompose_example(
        doc,
        "底面积为 0.02 m² 的薄壁容器装水深 30 cm 的水，求水对容器底的压强和压力（ρ水=10³ kg/m³，g=10 N/kg）。",
        [
            ("圈词", "S=0.02 m²；h=30 cm；求 p 和 F"),
            ("判类型", "液体压强 p=ρgh；F=pS"),
            ("找关系", "h=0.3 m；先 p 再 F"),
            ("列式", "p=10³×10×0.3；F=p×0.02"),
        ],
        "p=ρgh；F=pS",
        "隐藏：h 用 m；求的是**水对底**的压力，不是容器重",
        "p=**3000 Pa**；F=pS=3000×0.02=**60 N**",
    )
    add_exam_types(doc, [
        "p=F/S 与 p=ρgh 选用",
        "液体压强计算",
        "连通器原理",
        "大气压相关现象",
    ])


def _chapter_10(doc):
    add_chapter_title(doc, "第十章 浮力")

    add_concept_block(doc, [
        "**浮力 F浮**：液体或气体对浸在其中的物体的向上托力。",
        "**阿基米德原理**：F浮=G排=ρ液gV排；V排为**排开液体体积**。",
        "**完全浸没**：V排=V物。",
        "**浮沉条件**（浸没时）：F浮=G **悬浮**；F浮>G **上浮**；F浮<G **下沉**。",
        "**漂浮**：F浮=G；V排<V物；ρ物<ρ液。",
        "**应用**：轮船（空心增大 V排）、潜水艇（改变自身重力）、气球（改变平均密度）。",
    ])
    add_formula_block(doc, [
        ("阿基米德原理", "F浮 = ρ液gV排 = G排"),
        ("称重法", "F浮 = G − F示（弹簧测力计）"),
        ("浮沉", "ρ物 < ρ液 漂浮；ρ物 = ρ液 悬浮；ρ物 > ρ液 下沉"),
    ])
    add_method_block(doc, [
        "**求 F浮**：①阿基米德 ρ液gV排；②称重法 G−F示；③漂浮时 F浮=G。",
        "**求 V排**：水面上升体积；或 V排=V物（浸没）。",
    ])
    add_mistake_problems(doc, [
        (
            "物体下沉时浮力一定小于重力吗？",
            "浮力总是小于重力。",
            "**下沉过程** F浮<G；若用外力按住静止，仍 F浮<G；**完全浸没**后 F浮不变。",
        ),
        (
            "漂浮的木块，F浮与 G 关系？",
            "F浮>G 因为浮着。",
            "漂浮时 **F浮=G**（二力平衡）。",
        ),
    ])
    add_exam_types(doc, [
        "阿基米德原理计算",
        "浮沉条件判断",
        "排水法与浮力结合",
        "密度计、轮船原理",
    ])


def _chapter_11(doc):
    add_chapter_title(doc, "第十一章 功和机械能")

    add_concept_block(doc, [
        "**功 W**：力×在力方向上移动的距离；**W=Fs**；单位 **J（焦耳）**。",
        "**做功两个必要因素**：①有力；②在力方向上有距离。",
        "**功率 P**：做功快慢；**P=W/t**；单位 **W（瓦特）**。",
        "**动能**：与**质量、速度**有关；速度越大、质量越大，动能越大。",
        "**重力势能**：与**质量、高度**有关；被举越高、质量越大，势能越大。",
        "**弹性势能**：形变程度越大，弹性势能越大。",
        "**机械能**：动能+势能；**守恒**（忽略摩擦等，动能势能可相互转化）。",
    ])
    add_formula_block(doc, [
        ("功", "W = Fs"),
        ("功率", "P = W/t = Fs/t"),
        ("滑轮（功的关系）", "不计摩擦时 W动=W总"),
    ])
    add_exam_types(doc, [
        "判断是否做功",
        "W=Fs、P=W/t 计算",
        "动能势能影响因素",
        "滚摆、单摆能量转化",
    ])


def _chapter_12(doc):
    add_chapter_title(doc, "第十二章 简单机械")

    add_concept_block(doc, [
        "**杠杆**：F₁l₁=F₂l₂；l 为**力臂**（支点到力的作用线的垂直距离）。",
        "**省力杠杆**：l₁>l₂（钳子、开瓶器）；**费力杠杆**：l₁<l₂（筷子、镊子）。",
        "**定滑轮**：改变方向，不省力（F=G）。",
        "**动滑轮**：省一半力（F=G/2），费距离。",
        "**滑轮组**：F=G/n（n 为承担动滑轮的绳段数）；s绳=ns物。",
        "**机械效率 η**：η=W有/W总×100%；η<1。",
    ])
    add_formula_block(doc, [
        ("杠杆平衡", "F₁l₁ = F₂l₂"),
        ("滑轮组", "F = (G+G动)/n（计动滑轮重）"),
        ("机械效率", "η = W有/W总 = G·h/(F·s)"),
    ])
    add_exam_types(doc, [
        "杠杆力臂作图与计算",
        "滑轮组省力判断",
        "机械效率计算",
    ])


