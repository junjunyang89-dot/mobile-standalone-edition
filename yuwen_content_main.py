        "野马奔腾的雾气，飞扬的尘埃，都是生物用气息互相吹拂的结果。"
        "天色湛蓝，是它真正的颜色吗？还是因为天空高远而看不到尽头呢？"
        "鹏从高空往下看，也不过像这个样子罢了。",
        notes="课标60篇。借鲲鹏变化说明万物有所待；"
