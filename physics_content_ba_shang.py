def _chapter_1(doc):
    add_chapter_title(doc, "第一章 机械运动")
    add_plain(doc, "★ **物理计算第一站**：单位换算 + v=s/t，务必练熟。")

    add_section_title(doc, "1.1", "长度和时间的测量")
    add_concept_block(doc, [
        "**长度单位**：国际单位 **米（m）**；常用 km、dm、cm、mm、μm、nm。",
        "**测量工具**：刻度尺；使用前看**量程、分度值、零刻度线**是否磨损。",
        "**读数**：视线**垂直**刻度；估读到分度值**下一位**（如分度值1 mm，读 3.45 cm）。",
        "**误差**：测量值与真实值之差；**不可避免**，只能减小（多次测量取平均、改进工具）。",
        "**错误**：操作不当造成，**可以避免**；误差≠错误。",
        "**时间单位**：国际单位 **秒（s）**；停表读数：先读分钟再读秒。",
    ])
    add_method_block(doc, [
        "**刻度尺使用**：选合适量程 → 放正（有刻度一侧贴物） → 视线垂直 → 估读。",
        "**多次测量求平均**：减小偶然误差；若某次数据偏差过大，应舍弃再测。",
    ])
    add_errors(doc, [
        "读数时视线不垂直 → 产生**错误**，不是误差。",
        "零刻度线磨损可从整刻度开始测，**减去偏移量**。",
        "停表小盘单位是**分钟**，不是秒。",
    ])
    add_exam_types(doc, [
        "刻度尺读数（估读位）",
        "误差与错误的区别",
        "多次测量取平均",
    ])

    add_section_title(doc, "1.2", "运动的描述")
    add_concept_block(doc, [
        "**机械运动**：物体位置随时间的变化。",
        "**参照物**：判断运动静止时选定的标准物体；**参照物默认选地面**。",
        "**相对性**：同一物体相对不同参照物，运动状态可能不同（如乘客相对车静止、相对地面运动）。",
        "**路程**：运动轨迹的长度，标量，单位 m。",
        "**位移**：从初位置到末位置的有向线段（高中重点；初中常考路程）。",
        "**速度**：表示运动快慢；**匀速直线运动**：速度大小方向不变。",
        "**变速运动**：速度大小或方向发生变化；初中常用**平均速度** v̄ = 总路程/总时间 描述。",
        "**频闪照片**：等时间间隔拍照；相邻位置**间距相等→匀速**；**间距越来越大→加速**（小球下落经典题）。",
    ])
    add_formula_block(doc, [
        ("速度定义", "v = s/t"),
        ("路程", "s = vt"),
        ("时间", "t = s/v"),
        ("单位换算", "1 m/s = 3.6 km/h；km/h → m/s 除以 3.6"),
    ])
    add_method_block(doc, [
        "**比较快慢**：①相同时间比路程；②相同路程比时间；③比速度 v。",
        "**s-t 图像**：过原点直线→**匀速**，斜率=速度；曲线向上弯→**变速（加速）**；水平线→**静止**。",
        "**v-t 图像**：水平线→匀速，v 为纵坐标读数；与 t 轴围成面积=路程（拓展）。",
        "**平均速度**：v̄ = s总/t总；往返不同速度时**不能**简单 (v1+v2)/2。",
        "**过桥过隧道**：「完全通过」路程 = **桥长 + 车长**。",
    ])
    add_mistake_problems(doc, [
        (
            "小明以 5 m/s 跑 100 m 用时多少？",
            "直接用 100÷5，未注意单位。",
            "t = s/v = 100 m / 5 m/s = **20 s**。",
        ),
        (
            "汽车 72 km/h 合多少 m/s？",
            "72÷3.6 算成 20 或 252。",
            "72 ÷ 3.6 = **20 m/s**（km/h 换 m/s **除以** 3.6）。",
        ),
        (
            "说「坐在座位上的乘客是静止的」，参照物是什么？",
            "答地面或答自己。",
            "参照物是**车（或座位）**；相对地面乘客在动。",
        ),
    ])
    add_decompose_example(
        doc,
        "一辆汽车在高速上匀速行驶，10 min 通过 15 km 的路程，求汽车速度（km/h 和 m/s）。",
        [
            ("圈词", "匀速；t=10 min；s=15 km；求 v"),
            ("判类型", "机械运动 → v=s/t"),
            ("找关系", "t=10 min=1/6 h；或先算 km/h 再换 m/s"),
            ("列式", "v=15 km/(1/6 h)=90 km/h；90÷3.6=25 m/s"),
        ],
        "v = s/t",
        "隐藏：10 min 需换成 h（或统一用 s 和 m）",
        "v = 15/(10/60) = **90 km/h** = **25 m/s**",
    )
    add_exam_types(doc, [
        "参照物判断运动静止",
        "v=s/t 计算及单位换算",
        "s-t / v-t 图像判断匀速还是变速",
        "频闪照片判断小球下落是否加速",
        "平均速度（多段行程、往返）",
        "过桥过隧道（路程=车长+桥长）",
        "相向相遇、同向追及",
    ])


def _chapter_2(doc):
    add_chapter_title(doc, "第二章 声现象")

    add_concept_block(doc, [
        "**产生**：物体**振动**产生声；振动停止，发声停止。",
        "**传播**：需要**介质**（固、液、气）；**真空不能传声**。",
        "**声速**：15℃ 空气中约 **340 m/s**；一般 **v固 > v液 > v气**。",
        "**音调**：由振动**频率**决定；频率高→音调高（尖）。",
        "**响度**：由振动**振幅**决定；振幅大→响度大。",
        "**音色**：由发声体材料和结构决定；用于区分不同乐器。",
        "**超声波**：频率 > 20000 Hz；**次声波**：频率 < 20 Hz。",
        "**噪声**：妨碍人们正常休息、学习、工作的声音；从**声源处、传播过程中、人耳处**减弱。",
    ])
    add_experiment_block(doc, [
        "**真空罩实验**：逐渐抽气，铃声变小 → 说明真空不能传声（理想推理）。",
        "**探究音调**：钢尺伸出桌面长度不同，振动频率不同 → 音调不同。",
        "**示波器**：波形疏→频率低→音调低；波形幅度大→响度大。",
    ])
    add_mistake_problems(doc, [
        (
            "用大小不同的力拨同一琴弦，改变的是音调还是响度？",
            "答音调。",
            "改变**振幅** → **响度**；音调由频率（弦的松紧、长短）决定。",
        ),
        (
            "「闻其声知其人」说明声的什么特性？",
            "答响度或音调。",
            "说明**音色**不同。",
        ),
    ])
    add_exam_types(doc, [
        "音调、响度、音色的区分",
        "声的产生与传播条件",
        "噪声防治的三个环节",
        "计算：打雷闪电（见光时间忽略，用 s=vt 算距离）",
    ])


def _chapter_3(doc):
    add_chapter_title(doc, "第三章 物态变化")

    add_concept_block(doc, [
        "**固、液、气** 三种物态；物态变化**吸热或放热**。",
        "**熔化**：固→液，**吸热**；**凝固**：液→固，**放热**。",
        "**晶体**（冰、海波、金属）：有固定**熔点**；熔化时**吸热但温度不变**。",
        "**非晶体**（蜡、玻璃）：无固定熔点；熔化时**持续吸热、温度上升**。",
        "**汽化**：液→气，**吸热**；方式：**蒸发**（任何温度、表面）和**沸腾**（达到沸点、内部和表面）。",
        "**液化**：气→液，**放热**；方法：降温、压缩体积。",
        "**升华**：固→气，吸热（冰雕变小、樟脑丸）；**凝华**：气→固，放热（霜、雾凇）。",
        "**白气**：不是水蒸气（看不见），是水蒸气**液化**成的小水珠。",
    ])
    add_table(doc, ["物态变化", "过程", "吸/放热", "举例"], [
        ["熔化", "固→液", "吸热", "冰化水"],
        ["凝固", "液→固", "放热", "水结冰"],
        ["汽化", "液→气", "吸热", "晾干衣服"],
        ["液化", "气→液", "放热", "露水、白气"],
        ["升华", "固→气", "吸热", "冻衣服变干"],
        ["凝华", "气→固", "放热", "霜"],
    ], [2, 2, 2, 5])
    add_experiment_block(doc, [
        "**晶体熔化图像**：AB 固态升温 → BC 熔化（温度不变=熔点） → CD 液态升温。",
        "**沸腾**：液体达到沸点且继续吸热；沸点与气压有关（气压高→沸点高）。",
        "**探究蒸发快慢**：控制变量——温度、表面积、空气流动。",
    ])
    add_errors(doc, [
        "水蒸气**看不见**；「白气」是**液化**的小水滴。",
        "晶体熔化时**温度不变**但仍**吸热**（内能增加）。",
        "霜是**凝华**，不是凝固。",
    ])
    add_exam_types(doc, [
        "判断吸热还是放热",
        "晶体与非晶体熔化图像",
        "生活现象属于哪种物态变化",
        "影响蒸发快慢的因素（控制变量表述）",
    ])


def _chapter_4(doc):
    add_chapter_title(doc, "第四章 光现象")

    add_concept_block(doc, [
        "**光源**：自身能发光的物体（太阳、灯、火焰；月亮不是光源）。",
        "**光在同种均匀介质中沿直线传播**；现象：影子、日食月食、小孔成像。",
        "**小孔成像**：倒立实像；像大小与孔到屏距离有关。",
        "**光的反射定律**：三线共面；反射角=入射角；光路**可逆**。",
        "**镜面反射**：平行入射→平行反射（水面、平面镜）。",
        "**漫反射**：平行入射→向各方向反射；仍遵守反射定律。",
        "**平面镜成像**：正立**虚像**；像与物**大小相等**；像距=物距；像与物关于镜面对称。",
        "**折射**：光从空气斜射入水/玻璃，折射角**小于**入射角；从水射入空气则相反。",
        "**看水中物体变浅**：光从水进入空气发生折射，看到的位置是**虚像**，比实际**浅**。",
    ])
    add_method_block(doc, [
        "**作图**：反射——画法线、标角度；平面镜——找对称点、连虚像。",
        "**作图题**：实线=实际光线；虚线=法线、辅助线、虚像。",
    ])
    add_mistake_problems(doc, [
        (
            "平面镜远离时，像的大小如何变化？",
            "像变小。",
            "像与物**始终等大**；远离时只是**像距变大**，视觉上「看起来小」。",
        ),
        (
            "漫反射遵守反射定律吗？",
            "不遵守，因为方向乱。",
            "**遵守**；每条光线都遵守，只是反射面不平。",
        ),
    ])
    add_exam_types(doc, [
        "反射定律作图",
        "平面镜成像特点判断",
        "小孔成像性质",
        "折射现象解释（筷子「弯折」、池水变浅）",
    ])


def _chapter_5(doc):
    add_chapter_title(doc, "第五章 透镜及其应用")

    add_concept_block(doc, [
        "**凸透镜**：中间厚边缘薄；**会聚**作用。",
        "**凹透镜**：中间薄边缘厚；**发散**作用。",
        "**焦点 F**：平行于主光轴的光线经凸透镜会聚点；**焦距 f**。",
        "**三条特殊光线**（凸透镜）：①平行主光轴→过焦点；②过焦点→平行主光轴；③过光心→方向不变。",
        "**成像规律**（凸透镜）：",
        "　· u>2f：**倒立、缩小、实像**（照相机）",
        "　· u=2f：倒立、等大、实像",
        "　· f<u<2f：**倒立、放大、实像**（投影仪）",
        "　· u=f：不成像（平行光）",
        "　· u<f：**正立、放大、虚像**（放大镜）",
        "**实像**：能呈现在光屏上；**虚像**：不能，只能用眼睛看。",
        "**眼睛**：晶状体相当于凸透镜；**近视**——像成在视网膜前，戴**凹透镜**；**远视**——像成在视网膜后，戴**凸透镜**。",
    ])
    add_table(doc, ["物距 u", "像的性质", "应用"], [
        ["u>2f", "倒立缩小实像", "照相机"],
        ["f<u<2f", "倒立放大实像", "投影仪"],
        ["u<f", "正立放大虚像", "放大镜"],
    ], [2.5, 4, 4])
    add_experiment_block(doc, [
        "**探究凸透镜成像**：蜡烛-透镜-光屏，等高调节；",
        "当 u>f 时移动光屏找清晰像；u<f 时屏上无像，从透镜另一侧观察虚像。",
    ])
    add_errors(doc, [
        "实像**倒立**，虚像**正立**——不要记反。",
        "u=f 时**不成像**，不是成等大像。",
        "近视用**凹透镜**发散，不是凸透镜。",
    ])
    add_exam_types(doc, [
        "根据 u 判断像的性质",
        "照相机/投影仪/放大镜对应物距范围 ★",
        "特殊光线作图",
        "近视远视成因与矫正",
    ])


def _chapter_6(doc):
    add_chapter_title(doc, "第六章 质量与密度")
    add_plain(doc, "★ **八上计算核心**：ρ=m/V + 单位换算 + 排水法测体积。")

    add_concept_block(doc, [
        "**质量 m**：物体所含物质的多少；国际单位 **kg**；属性，不随位置形状改变（状态变可能变）。",
        "**天平**：测质量；**左物右码**；游码读数+砝码；**不能直接测化学药品、潮湿物品**。",
        "**量筒**：测液体体积或**排水法**测固体体积。",
        "**密度 ρ**：单位体积某种物质的质量；ρ=m/V；国际单位 **kg/m³**；ρ水=1.0×10³ kg/m³=1 g/cm³。",
        "**密度是物质特性**：同种物质 ρ 相同（一般）；不同物质 ρ 一般不同。",
    ])
    add_formula_block(doc, [
        ("密度", "ρ = m/V"),
        ("质量", "m = ρV"),
        ("体积", "V = m/ρ"),
        ("单位", "1 g/cm³ = 10³ kg/m³"),
    ])
    add_method_block(doc, [
        "**测固体密度**：天平测 m → 量筒排水法测 V → ρ=m/V。",
        "**测液体密度**：测烧杯+液体总质量 m₁ → 倒部分到量筒测 V → 测剩余 m₂ → m液=m₁−m₂。",
        "**空心问题**：若 ρ算 < ρ材料，则为空心；V实=m/ρ材料。",
        "**比例题**：同种物质 m₁/m₂ = V₁/V₂。",
    ])
    add_mistake_problems(doc, [
        (
            "体积 200 cm³、质量 540 g 的金属块密度？（kg/m³）",
            "直接用 540/200=2.7，单位当 kg/m³。",
            "ρ=540g/(200cm³)=2.7 g/cm³=**2.7×10³ kg/m³**；或换 0.54 kg 与 2×10⁻⁴ m³ 计算。",
        ),
        (
            "将冰熔化成水，质量与密度如何变？",
            "质量和密度都不变。",
            "**质量不变**；密度变大（水比冰密）。",
        ),
    ])
    add_decompose_example(
        doc,
        "一空瓶质量 200 g，装满水总质量 700 g；若装满某液体总质量 660 g，求该液体密度。",
        [
            ("圈词", "m瓶=200 g；m水总=700 g；m液总=660 g"),
            ("判类型", "密度 → 先求 V瓶，再求 m液"),
            ("找关系", "V瓶=V水=m水/ρ水；m水=700−200=500 g"),
            ("列式", "ρ液=m液/V=(660−200)/V"),
        ],
        "V = m/ρ；ρ液 = m液/V；**同一瓶子容积相等**",
        "隐藏：V瓶=V水；m水=500 g → V=500 cm³；m液=460 g",
        "ρ液 = 460 g / 500 cm³ = **0.92 g/cm³**",
    )
    add_advanced_problems(doc, [
        (
            "三个相同杯子，分别装满水、酒精、水银，比较它们对杯底的压力（ρ酒精<ρ水<ρ水银）。",
            "F=pS，p=ρgh，h相同比 ρ；F=G=mg=ρVg，V相同比 ρ。",
            "F水银 > F水 > F酒精",
        ),
        (
            "铝块投入量筒水中，水面从 50 mL 升到 70 mL，铝块质量 54 g，求密度。",
            "V排=20 cm³=V铝；ρ=54/20=2.7 g/cm³。",
            "ρ = **2.7 g/cm³**",
        ),
    ])
    add_exam_types(doc, [
        "ρ=m/V 计算与单位换算",
        "天平量筒实验步骤",
        "空心球判断",
        "m-V 图像求密度（斜率=ρ）",
    ])


